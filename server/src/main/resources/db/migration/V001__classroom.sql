CREATE TABLE accounts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username TEXT UNIQUE NOT NULL,
    full_name TEXT NOT NULL,
    role TEXT NOT NULL CHECK(role IN ('TEACHER','STUDENT')),
    password_hash TEXT NOT NULL,
    salt TEXT NOT NULL,
    enabled BIGINT NOT NULL DEFAULT 1
);

CREATE TABLE class_sessions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    type TEXT NOT NULL CHECK(type IN ('CLASS','EXAM')),
    teacher_id BIGINT NOT NULL REFERENCES accounts(id),
    started_at BIGINT NOT NULL,
    ended_at BIGINT
);

CREATE TABLE student_sessions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id BIGINT NOT NULL REFERENCES accounts(id),
    machine_id TEXT NOT NULL,
    agent_session TEXT NOT NULL,
    class_id BIGINT NOT NULL REFERENCES class_sessions(id),
    signed_in_at BIGINT NOT NULL,
    last_seen_at BIGINT NOT NULL,
    ended_at BIGINT,
    end_reason TEXT
);

CREATE UNIQUE INDEX active_student ON student_sessions(account_id) WHERE ended_at IS NULL;

CREATE UNIQUE INDEX active_machine ON student_sessions(machine_id) WHERE ended_at IS NULL;

CREATE TABLE activity_records (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_session_id BIGINT NOT NULL REFERENCES student_sessions(id),
    kind TEXT NOT NULL CHECK(kind IN ('WEB','PROCESS')),
    source_key TEXT NOT NULL,
    details TEXT NOT NULL,
    source_at BIGINT NOT NULL,
    observed_at BIGINT NOT NULL,
    UNIQUE(student_session_id,kind,source_key)
);

CREATE TABLE violations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_session_id BIGINT NOT NULL REFERENCES student_sessions(id),
    details TEXT NOT NULL,
    occurred_at BIGINT NOT NULL,
    status TEXT NOT NULL DEFAULT 'FLAGGED',
    penalty_points BIGINT NOT NULL DEFAULT 0,
    note TEXT NOT NULL DEFAULT '',
    teacher_id BIGINT NOT NULL REFERENCES accounts(id),
    updated_at BIGINT NOT NULL
);

CREATE TABLE teacher_actions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    teacher_id BIGINT NOT NULL REFERENCES accounts(id),
    violation_id BIGINT REFERENCES violations(id),
    action TEXT NOT NULL,
    previous_value TEXT,
    new_value TEXT,
    at BIGINT NOT NULL
);

CREATE TABLE system_errors (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_session_id BIGINT NOT NULL REFERENCES student_sessions(id),
    code TEXT NOT NULL,
    message TEXT NOT NULL,
    first_seen_at BIGINT NOT NULL,
    last_seen_at BIGINT NOT NULL,
    resolved_at BIGINT,
    occurrence_count BIGINT NOT NULL DEFAULT 1
);

CREATE UNIQUE INDEX active_error ON system_errors(student_session_id,code) WHERE resolved_at IS NULL;

CREATE INDEX activities_by_session ON activity_records(student_session_id,observed_at);

CREATE TABLE connection_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    machine_id TEXT NOT NULL,
    machine_name TEXT NOT NULL,
    ip TEXT NOT NULL,
    event TEXT NOT NULL CHECK(event IN ('ONLINE','OFFLINE')),
    at_epoch_ms BIGINT NOT NULL
);

CREATE INDEX idx_events_machine ON connection_events(machine_id,at_epoch_ms);
