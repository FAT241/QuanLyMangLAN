CREATE TABLE exam_attempts (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 class_id BIGINT NOT NULL REFERENCES class_sessions(id),
 account_id BIGINT NOT NULL REFERENCES accounts(id),
 started_at BIGINT NOT NULL,
 submitted_at BIGINT,
 closed_at BIGINT,
 end_reason TEXT,
 UNIQUE(class_id,account_id)
);
CREATE TABLE monitor_rules (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 class_id BIGINT NOT NULL REFERENCES class_sessions(id),
 kind TEXT NOT NULL CHECK(kind IN ('WEB','PROCESS')),
 pattern TEXT NOT NULL,
 enabled BIGINT NOT NULL DEFAULT 1,
 UNIQUE(class_id,kind,pattern)
);
CREATE TABLE rule_alerts (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 rule_id BIGINT NOT NULL REFERENCES monitor_rules(id),
 activity_id BIGINT NOT NULL REFERENCES activity_records(id),
 created_at BIGINT NOT NULL,
 UNIQUE(rule_id,activity_id)
);
CREATE TABLE account_actions (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 teacher_id BIGINT NOT NULL REFERENCES accounts(id),
 account_id BIGINT NOT NULL REFERENCES accounts(id),
 action TEXT NOT NULL,
 at BIGINT NOT NULL
);
CREATE TABLE rule_scan_offsets (
 rule_id BIGINT NOT NULL REFERENCES monitor_rules(id),
 student_session_id BIGINT NOT NULL REFERENCES student_sessions(id),
 last_activity_id BIGINT NOT NULL,
 PRIMARY KEY(rule_id,student_session_id)
);
CREATE INDEX visits_by_time ON activity_records(student_session_id,source_at,id);
CREATE INDEX errors_by_time ON system_errors(student_session_id,first_seen_at,id);
